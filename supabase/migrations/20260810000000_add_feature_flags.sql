-- Per-user feature flags: dim_features (global registry) + dim_features_users (per-user state).
--
-- Mirrors the dim_categories -> dim_categories_users pattern: a global template table plus a
-- per-user table seeded on signup by a trigger on auth.users.
--
-- Flags are granted, not self-served: dim_features_users has a SELECT policy only. Writes come
-- from the security-definer seed trigger below (owner bypasses RLS) and from the SQL editor.


-- ================================================================================================
--                                   dim_features (global registry)
-- ================================================================================================

CREATE TABLE "public"."dim_features" (
    "features_id_pk"      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "feature_key"         text NOT NULL UNIQUE,
    "feature_name"        text NOT NULL,
    "feature_description" text,
    "is_active"           boolean NOT NULL DEFAULT true,
    "created_at"          timestamp with time zone NOT NULL DEFAULT now()
);

ALTER TABLE "public"."dim_features" ENABLE ROW LEVEL SECURITY;

-- Read-only for every authenticated user; no write policies, so writes are migration-only.
-- Same shape as dim_exchange_rates.
CREATE POLICY "Select features" ON "public"."dim_features"
    FOR SELECT TO "authenticated" USING (true);


-- ================================================================================================
--                                dim_features_users (per-user state)
-- ================================================================================================

CREATE TABLE "public"."dim_features_users" (
    "features_users_id_pk" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user_id_fk"           uuid NOT NULL DEFAULT auth.uid()
                               REFERENCES auth.users(id) ON DELETE CASCADE,
    "feature_key"          text NOT NULL
                               REFERENCES public.dim_features(feature_key) ON DELETE CASCADE,
    "is_enabled"           boolean NOT NULL DEFAULT false,
    "created_at"           timestamp with time zone NOT NULL DEFAULT now(),
    "updated_at"           timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "dim_features_users_unique" UNIQUE ("user_id_fk", "feature_key")
);

CREATE INDEX "dim_features_users_user_id_idx" ON "public"."dim_features_users" ("user_id_fk");

ALTER TABLE "public"."dim_features_users" ENABLE ROW LEVEL SECURITY;

-- SELECT only: a user must not be able to turn on their own features.
CREATE POLICY "Select own features" ON "public"."dim_features_users"
    FOR SELECT USING (("user_id_fk" = auth.uid()));


