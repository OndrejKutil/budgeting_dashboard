-- ================================================================================================
--                                   Seed trigger on signup
-- ================================================================================================

CREATE OR REPLACE FUNCTION "public"."seed_user_features"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET search_path = public, pg_temp
    AS $$
BEGIN
    INSERT INTO public.dim_features_users (user_id_fk, feature_key, is_enabled)
    SELECT NEW.id, f.feature_key, false
    FROM public.dim_features f
    WHERE f.is_active
    ON CONFLICT (user_id_fk, feature_key) DO NOTHING;

    RETURN NEW;
EXCEPTION WHEN OTHERS THEN
    -- Never block a signup over a feature flag. A missing row already reads as `false`.
    RAISE WARNING 'seed_user_features failed for user %: %', NEW.id, SQLERRM;
    RETURN NEW;
END;
$$;

ALTER FUNCTION "public"."seed_user_features"() OWNER TO "postgres";

CREATE TRIGGER "on_auth_user_created_seed_features"
    AFTER INSERT ON "auth"."users"
    FOR EACH ROW EXECUTE FUNCTION "public"."seed_user_features"();


-- ================================================================================================
--                                   Backfill existing users
-- ================================================================================================

INSERT INTO public.dim_features_users (user_id_fk, feature_key, is_enabled)
SELECT u.id, f.feature_key, false
FROM auth.users u
CROSS JOIN public.dim_features f
WHERE f.is_active
ON CONFLICT (user_id_fk, feature_key) DO NOTHING;


